#!/usr/bin/env python3
"""Headless self-check for Earp Street Park issue #7.

Asserts (against index.html served over a local http.server bound to
127.0.0.1, in a headless Chromium):

1. All four `.punch .what` plan titles render as `display: block` and
   their rendered title line ends with a colon (generated by
   `.punch .what::after { content: ":"; }`).
2. No overflow on the fixed-height Plan sheet: scrollHeight <= clientHeight
   on the plan note in BOTH the collapsed and expanded states, at desktop
   (~1280px) and at the file's mobile breakpoint (max-width: 760px).
   The open panel itself is the page's one designed scroll container
   (overflow-y: auto on main) and already scrolls on untouched main
   (measured: 635>549 desktop, 1091>700 mobile), so the script asserts the
   scroll path stays intact (overflow-y: auto — content reachable, never
   clipped) and prints the panel numbers for the record.
3. The `.need .what` "What it needs" list is unchanged: every title is a
   block, uppercase label with NO generated colon. (The task brief said
   4 need titles; main actually ships 3 — People, Materials, A truck — so
   the count is asserted against the markup's own <li> count.)

Exits 0 only when every assertion holds. Usage: python3 check_plan_titles.py
"""

import functools
import http.server
import os
import socketserver
import sys
import threading

from playwright.sync_api import sync_playwright

HERE = os.path.dirname(os.path.abspath(__file__))
VIEWPORTS = [
    (1280, 800, "desktop ~1280px"),
    (480, 860, "mobile breakpoint (max-width: 760px)"),
]
TRANSITION_SETTLE_MS = 700  # the sheets animate open over 450ms

failures = []


def check(label, ok, detail):
    tag = "PASS" if ok else "FAIL"
    print(f"[{tag}] {label} {detail}")
    if not ok:
        failures.append(label)


def metrics(page, selector):
    return page.evaluate(
        """(sel) => {
             const el = document.querySelector(sel);
             if (!el) return null;
             return { sh: el.scrollHeight, ch: el.clientHeight };
           }""",
        selector,
    )


def main():
    handler = functools.partial(
        http.server.SimpleHTTPRequestHandler, directory=HERE
    )
    socketserver.TCPServer.allow_reuse_address = True
    httpd = socketserver.TCPServer(("127.0.0.1", 0), handler)
    port = httpd.server_address[1]
    threading.Thread(target=httpd.serve_forever, daemon=True).start()
    url = f"http://127.0.0.1:{port}/index.html"

    try:
        with sync_playwright() as p:
            browser = p.chromium.launch(headless=True)
            for width, height, label in VIEWPORTS:
                page = browser.new_page(viewport={"width": width, "height": height})
                page.goto(url)
                page.wait_for_load_state("load")

                # --- criterion 1: plan titles block + generated colon ---
                titles = page.query_selector_all(".punch .what")
                check("c1", len(titles) == 4, f"plan titles found: {len(titles)} (want 4) @ {label}")
                for i, el in enumerate(titles):
                    display = el.evaluate("e => getComputedStyle(e).display")
                    colon = el.evaluate("e => getComputedStyle(e, '::after').content")
                    check(
                        "c1",
                        display == "block" and colon == '":"',
                        f"title[{i}] '{el.inner_text().strip()}' display={display} ::after={colon} @ {label}",
                    )

                # --- criterion 3: .need list unchanged (block, uppercase, no colon) ---
                needs = page.query_selector_all(".need .what")
                need_li_count = page.evaluate(
                    "document.querySelectorAll('.need > li').length"
                )
                check(
                    "c3",
                    len(needs) == need_li_count == 3,
                    f"need titles found: {len(needs)} vs {need_li_count} <li> in ul.need (main ships 3) @ {label}",
                )
                for i, el in enumerate(needs):
                    display = el.evaluate("e => getComputedStyle(e).display")
                    upper = el.evaluate("e => getComputedStyle(e).textTransform")
                    colon = el.evaluate("e => getComputedStyle(e, '::after').content")
                    check(
                        "c3",
                        display == "block" and upper == "uppercase" and colon == "none",
                        f"need[{i}] '{el.inner_text().strip()}' display={display} "
                        f"text-transform={upper} ::after={colon} @ {label}",
                    )

                # --- criterion 2: no overflow, collapsed then expanded ---
                note_sel = "#panel-plan"
                note = page.evaluate(
                    "document.getElementById('panel-plan').closest('.note') !== null"
                )
                check("c2", note, "plan note located @ " + label)

                def assert_no_overflow(state):
                    n = metrics(page, "#panel-plan")  # note via panel's ancestor
                    note_box = page.evaluate(
                        """() => {
                             const note = document.getElementById('panel-plan').closest('.note');
                             return { sh: note.scrollHeight, ch: note.clientHeight };
                           }"""
                    )
                    panel_box = metrics(page, "#panel-plan") or {"sh": 0, "ch": 0}
                    check(
                        "c2",
                        note_box["sh"] <= note_box["ch"],
                        f"plan note {state}: scrollHeight={note_box['sh']} <= clientHeight={note_box['ch']} @ {label}",
                    )
                    # the open panel is the designed scroll container (overflow-y: auto
                    # on untouched main, which already scrolls): content must stay
                    # reachable, never clipped
                    overflow_y = page.evaluate(
                        "getComputedStyle(document.getElementById('panel-plan')).overflowY"
                    )
                    check(
                        "c2",
                        state == "collapsed" or overflow_y == "auto",
                        f"plan panel {state}: overflow-y={overflow_y} (auto = scrollable, not clipped) "
                        f"scrollHeight={panel_box['sh']} clientHeight={panel_box['ch']} @ {label}",
                    )

                assert_no_overflow("collapsed")

                page.click(".note--plan .note-toggle")
                page.wait_for_timeout(TRANSITION_SETTLE_MS)
                expanded = page.evaluate(
                    "document.getElementById('panel-plan').closest('.note').classList.contains('expanded')"
                )
                check("c2", expanded, "plan note expanded @ " + label)
                assert_no_overflow("expanded")
                page.close()
            browser.close()
    finally:
        httpd.shutdown()
        httpd.server_close()

    if failures:
        print(f"\n{len(failures)} check(s) FAILED")
        return 1
    print("\nAll checks passed")
    return 0


if __name__ == "__main__":
    sys.exit(main())